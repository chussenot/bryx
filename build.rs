//! Renders BRYX's two soundtracks at build time with Sonomorph, the crate
//! BRYX's sound engines were extracted to.
//!
//! Only with the `audio` feature (on by default):
//! - the orchestral soundtrack, with the studio (`sonomorph::advanced`):
//!   1. every `audio/score/*.score` (the music and the stingers) to 48 kHz
//!      stereo QOA, `OUT_DIR/<name>.qoa`, listed in `OUT_DIR/scores.rs`;
//!   2. every `audio/score/sfx/*.score` (the effects), brought down to mono
//!      at [`SAMPLE_RATE`], trimmed of trailing silence and encoded to
//!      `OUT_DIR/<name>.ulaw`, 8-bit mu-law, listed in `OUT_DIR/cues.rs`;
//! - the 8-bit soundtrack, with the chip8 engine (`sonomorph::chip8`):
//!   every `audio/cues/*.abc` (music, stingers and effects) to 16-bit mono
//!   at [`SAMPLE_RATE`], encoded to `OUT_DIR/chip_<name>.ulaw`, listed in
//!   `OUT_DIR/chip.rs`.
//!
//! So both engines are build tools: the game binary carries rendered audio
//! and runs no C. A sound is a `.score` or `.abc` text file; rebuilding
//! re-renders it, deterministically. Studio renders are cached in
//! `OUT_DIR` by content; the chip8 engine renders all 56 cues in seconds.

#[cfg(feature = "audio")]
use std::path::{Path, PathBuf};

/// Matches `src/audio/cues.rs`'s `CUE_SAMPLE_RATE`: the effects' rate,
/// one byte a sample at half CD rate.
#[cfg(feature = "audio")]
const SAMPLE_RATE: u32 = 22_050;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    compile_shaders();
    cue_meters();
    track_modes();
    #[cfg(feature = "audio")]
    render_cues();
    #[cfg(feature = "audio")]
    render_chip();
}

/// The meter of the cues the visuals land on (`src/cadence.rs`): each
/// one's bar length and beats per bar, read from its score, so a visual
/// that follows the music cannot drift from it when a cue is rewritten. A
/// stinger's meter is its tempo (four beats to the bar); an effect, whose
/// score counts in seconds, states it in a `# meter <bar seconds> <beats>`
/// line. The 8-bit cue of the same name must keep the same meter (its
/// `M:` and `Q:` headers): the visuals follow one beat whichever
/// soundtrack plays. Text only: built with or without the `audio` feature.
fn cue_meters() {
    let mut out = String::from("// Generated by build.rs from audio/score. Do not edit.\n");
    for (name, path, abc) in [
        (
            "LEVEL_CLEAR",
            "audio/score/level_clear.score",
            "audio/cues/level_clear.abc",
        ),
        ("WARP", "audio/score/sfx/warp.score", "audio/cues/warp.abc"),
    ] {
        println!("cargo:rerun-if-changed={path}");
        let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}"));
        let line = |prefix: &str| text.lines().find_map(|l| l.strip_prefix(prefix));
        let (bar, beats) = if let Some(meter) = line("# meter ") {
            let mut fields = meter.split_whitespace();
            let bar: f64 = fields
                .next()
                .and_then(|v| v.parse().ok())
                .expect("# meter <bar seconds>");
            let beats: u32 = fields
                .next()
                .and_then(|v| v.parse().ok())
                .expect("# meter <beats>");
            (bar, beats)
        } else {
            let bpm: f64 = line("tempo 0 ")
                .and_then(|v| v.trim().parse().ok())
                .unwrap_or_else(|| panic!("{path}: no `tempo 0 <bpm>` line"));
            (4.0 * 60.0 / bpm, 4)
        };
        let (abc_bar, abc_beats) = abc_meter(abc);
        assert!(
            (abc_bar - bar).abs() < 1e-9 && abc_beats == beats,
            "{abc} keeps a {abc_bar} s bar of {abc_beats} beats and {path} a {bar} s bar \
             of {beats}: the visuals follow one beat for both soundtracks"
        );
        out.push_str(&format!(
            "pub const {name}: Meter = Meter {{ bar: {bar:?}, beats: {beats} }};\n"
        ));
    }
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    std::fs::write(format!("{out_dir}/cue_meters.rs"), out).expect("write cue_meters.rs");
}

/// An 8-bit cue's bar length in seconds and beats per bar, from its ABC
/// headers: `M:4/4` is the bar in whole notes, `Q:1/4=160` is 160 quarter
/// notes a minute.
fn abc_meter(path: &str) -> (f64, u32) {
    println!("cargo:rerun-if-changed={path}");
    let abc = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}"));
    let field = |key: &str| {
        abc.lines()
            .find_map(|l| l.strip_prefix(key))
            .map(str::trim)
            .unwrap_or_else(|| panic!("{path}: no {key} header"))
    };
    let ratio = |text: &str| -> f64 {
        let (n, d) = text.split_once('/').unwrap_or((text, "1"));
        n.trim().parse::<f64>().expect("meter numerator")
            / d.trim().parse::<f64>().expect("meter denominator")
    };
    let meter = field("M:");
    let beats: u32 = meter.split('/').next().unwrap().trim().parse().expect("M:");
    let (unit, bpm) = field("Q:").split_once('=').expect("Q: as unit=bpm");
    let bar = ratio(meter) * 60.0 / (ratio(unit) * bpm.trim().parse::<f64>().expect("Q: bpm"));
    (bar, beats)
}

/// The mode each level track is written in, read from the `# mode E <mode>`
/// line of its score (`audio/compose_studio.py`), so the rally's scale
/// (`src/audio/director.rs`) follows a track when it is recomposed. The
/// 8-bit track of the same level names its mode in a `% mode E <mode>,`
/// line (`audio/compose.py`), and it must be the same one: the rally
/// harmonizes with whichever soundtrack plays. Text only, like
/// `cue_meters`.
fn track_modes() {
    let mut modes = Vec::new();
    for n in 1.. {
        let path = format!("audio/score/music_{n:02}.score");
        let Ok(text) = std::fs::read_to_string(&path) else {
            break;
        };
        println!("cargo:rerun-if-changed={path}");
        let mode = text
            .lines()
            .find_map(|l| l.strip_prefix("# mode E "))
            .unwrap_or_else(|| panic!("{path}: no `# mode E <mode>` line"));
        let abc = format!("audio/cues/music_{n:02}.abc");
        println!("cargo:rerun-if-changed={abc}");
        let chip = std::fs::read_to_string(&abc).unwrap_or_else(|e| panic!("{abc}: {e}"));
        let chip_mode = chip
            .lines()
            .find_map(|l| l.strip_prefix("% mode E "))
            .and_then(|m| m.split(',').next())
            .map(str::trim)
            .unwrap_or_else(|| panic!("{abc}: no `% mode E <mode>,` line"));
        assert_eq!(
            chip_mode,
            mode.trim(),
            "{abc} and {path} name different modes: the rally harmonizes with both"
        );
        modes.push(match mode.trim() {
            "dorian" => "Dorian",
            "aeolian" => "Aeolian",
            "phrygian" => "Phrygian",
            "harmonic" => "HarmonicMinor",
            other => panic!("{path}: unknown mode {other:?}"),
        });
    }
    let list: Vec<String> = modes.iter().map(|m| format!("Mode::{m}")).collect();
    let out = format!(
        "// Generated by build.rs from the level tracks' scores. Do not edit.\n\
         pub const LEVEL_MODES: &[Mode] = &[{}];\n",
        list.join(", ")
    );
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    std::fs::write(format!("{out_dir}/track_modes.rs"), out).expect("write track_modes.rs");
}

/// The effects' WESL shaders (`src/shaders/`), each entry module compiled
/// with its imports to one plain WGSL file in OUT_DIR, which `fx/gpu.rs`
/// `include_str!`s. Functions no entry point uses are stripped. A WESL
/// error fails the build with the compiler's own diagnostic.
fn compile_shaders() {
    println!("cargo:rerun-if-changed=src/shaders");
    for entry in ["fx_geometry", "bloom", "composite"] {
        let compiled = wesl::Compiler::default()
            .compile(format!("src/shaders/{entry}.wesl"))
            .inspect_err(|e| eprintln!("{e}"))
            .unwrap_or_else(|_| panic!("WESL: src/shaders/{entry}.wesl did not compile"));
        compiled.write_artifact(entry);
    }
}

#[cfg(feature = "audio")]
fn render_cues() {
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    println!("cargo:rerun-if-changed=audio");

    let effects = render_scores(&out_dir);

    // The effects: the studio's 16-bit stereo at twice the cue rate, down
    // to mono mu-law at it, filtered so nothing above the new Nyquist folds
    // (`sonomorph::advanced::fold_effect`).
    let mut table = String::from(
        "// Generated by build.rs from audio/score/sfx/*.score. Do not edit.\n\
         pub const CUES: &[(&str, &[u8])] = &[\n",
    );
    for (name, rendered) in &effects {
        let mut samples = sonomorph::advanced::fold_effect(&read_s16(rendered));
        // An effect loses the silence the studio renders after it (anything
        // under one 8-bit step), so a voice frees itself the moment its
        // sound ends.
        while samples.last().is_some_and(|s| s.unsigned_abs() <= 256) {
            samples.pop();
        }
        let pcm = out_dir.join(format!("{name}.ulaw"));
        let bytes: Vec<u8> = samples
            .into_iter()
            .map(sonomorph::chip8::mulaw::encode)
            .collect();
        std::fs::write(&pcm, bytes).expect("write encoded cue");
        table.push_str(&format!(
            "    ({name:?}, include_bytes!({:?})),\n",
            pcm.display().to_string()
        ));
    }
    table.push_str("];\n");
    std::fs::write(out_dir.join("cues.rs"), table).expect("write cues.rs");
}

/// The 8-bit soundtrack: every `audio/cues/*.abc` rendered by Sonomorph's
/// chip8 engine to 16-bit mono at [`SAMPLE_RATE`], in parallel (the engine
/// is reentrant), encoded to 8-bit mu-law in `OUT_DIR/chip_<name>.ulaw`
/// and listed in `OUT_DIR/chip.rs` in name order. Effects and stingers
/// lose the silence the engine renders after them (anything under one
/// 8-bit step), so a voice frees itself the moment its sound ends; music
/// loops keep their exact length, as the loop point depends on it. The
/// same bytes `master` embedded when this was BRYX's only soundtrack.
#[cfg(feature = "audio")]
fn render_chip() {
    use std::sync::atomic::{AtomicUsize, Ordering};

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let mut cues: Vec<PathBuf> = std::fs::read_dir("audio/cues")
        .expect("audio/cues")
        .filter_map(|entry| entry.ok().map(|e| e.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "abc"))
        .collect();
    cues.sort();
    let stem = |path: &Path| path.file_stem().unwrap().to_str().unwrap().to_owned();
    let encoded = |cue: &Path| out_dir.join(format!("chip_{}.ulaw", stem(cue)));

    let next = AtomicUsize::new(0);
    let workers = std::thread::available_parallelism().map_or(4, |n| n.get());
    std::thread::scope(|scope| {
        for _ in 0..workers.min(cues.len()) {
            scope.spawn(|| {
                while let Some(cue) = cues.get(next.fetch_add(1, Ordering::Relaxed)) {
                    let mut samples = sonomorph::chip8::render_file(cue, SAMPLE_RATE)
                        .unwrap_or_else(|err| panic!("rendering {}: {err}", cue.display()));
                    if !stem(cue).starts_with("music_") {
                        while samples.last().is_some_and(|s| s.unsigned_abs() <= 256) {
                            samples.pop();
                        }
                    }
                    let bytes: Vec<u8> = samples
                        .into_iter()
                        .map(sonomorph::chip8::mulaw::encode)
                        .collect();
                    std::fs::write(encoded(cue), bytes).expect("write encoded cue");
                }
            });
        }
    });

    let mut table = String::from(
        "// Generated by build.rs from audio/cues/*.abc. Do not edit.\n\
         pub const CHIP: &[(&str, &[u8])] = &[\n",
    );
    for cue in &cues {
        table.push_str(&format!(
            "    ({:?}, include_bytes!({:?})),\n",
            stem(cue),
            encoded(cue).display().to_string()
        ));
    }
    table.push_str("];\n");
    std::fs::write(out_dir.join("chip.rs"), table).expect("write chip.rs");
}

/// Signed 16-bit little-endian samples from a file.
#[cfg(feature = "audio")]
fn read_s16(path: &Path) -> Vec<i16> {
    std::fs::read(path)
        .unwrap_or_else(|e| panic!("{}: {e}", path.display()))
        .as_chunks::<2>()
        .0
        .iter()
        .map(|&b| i16::from_le_bytes(b))
        .collect()
}

/// The studio's renders, in parallel (a score takes seconds; the studio is
/// reentrant):
/// - the scores (`audio/score/*.score`: music and stingers) to QOA for the
///   game;
/// - the effects (`audio/score/sfx/*.score`) to 16-bit stereo at twice the
///   cue rate, which `render_cues` brings down to the mu-law effects path
///   (effects are pitched by playback rate, so they stay there); returned
///   as (name, render), in name order.
///
/// Any edit under `audio/` reruns this script, so each render is cached in
/// `OUT_DIR` under a key: the hash of the score and of everything a render
/// reads (BRYX's instruments, Sonomorph's library and engine). The studio
/// is deterministic, so an unchanged key is an unchanged render.
#[cfg(feature = "audio")]
fn render_scores(out_dir: &Path) -> Vec<(String, PathBuf)> {
    use std::hash::{DefaultHasher, Hash, Hasher};
    use std::sync::atomic::{AtomicUsize, Ordering};

    let list = |dir: &str| -> Vec<PathBuf> {
        let mut found: Vec<PathBuf> = std::fs::read_dir(dir)
            .map(|d| {
                d.filter_map(|entry| entry.ok().map(|e| e.path()))
                    .filter(|path| path.extension().is_some_and(|ext| ext == "score"))
                    .collect()
            })
            .unwrap_or_default();
        found.sort();
        found
    };
    let stem = |path: &Path| path.file_stem().unwrap().to_str().unwrap().to_owned();
    let scores: Vec<(PathBuf, PathBuf)> = list("audio/score")
        .into_iter()
        .map(|s| {
            let out = out_dir.join(format!("{}.qoa", stem(&s)));
            (s, out)
        })
        .collect();
    let effects: Vec<(PathBuf, PathBuf)> = list("audio/score/sfx")
        .into_iter()
        .map(|s| {
            let out = out_dir.join(format!("sfx_{}.s16", stem(&s)));
            (s, out)
        })
        .collect();
    let jobs: Vec<&(PathBuf, PathBuf)> = scores.iter().chain(&effects).collect();
    let effect_rate = 2 * SAMPLE_RATE;

    let library = Path::new(sonomorph::advanced::LIBRARY);
    let mut inputs = DefaultHasher::new();
    for root in [
        Path::new("audio/instruments"),
        library,
        &library.join("../engine"),
    ] {
        hash_tree(root, &mut inputs);
    }
    let inputs = inputs.finish();

    let next = AtomicUsize::new(0);
    let workers = std::thread::available_parallelism().map_or(4, |n| n.get());
    std::thread::scope(|scope| {
        for _ in 0..workers.min(jobs.len()) {
            scope.spawn(|| {
                while let Some((score, out)) = jobs.get(next.fetch_add(1, Ordering::Relaxed)) {
                    let key_file = out.with_extension("key");
                    let mut key = DefaultHasher::new();
                    inputs.hash(&mut key);
                    std::fs::read(score).expect("read score").hash(&mut key);
                    let key = format!("{:016x}", key.finish());
                    if out.exists() && std::fs::read_to_string(&key_file).is_ok_and(|k| k == key) {
                        continue;
                    }
                    let effect = out.extension().is_some_and(|e| e == "s16");
                    let render =
                        sonomorph::advanced::render_score(score, effect.then_some(effect_rate))
                            .unwrap_or_else(|e| panic!("rendering {}: {e}", score.display()));
                    let bytes: Vec<u8> = if effect {
                        render
                            .to_s16()
                            .iter()
                            .flat_map(|s| s.to_le_bytes())
                            .collect()
                    } else {
                        render.to_qoa()
                    };
                    std::fs::write(out, bytes).expect("write render");
                    std::fs::write(&key_file, key).expect("write render key");
                }
            });
        }
    });

    let table = |header: &str, name: &str, list: &[(PathBuf, PathBuf)]| {
        let mut t = format!("// Generated by build.rs from {header}. Do not edit.\npub const {name}: &[(&str, &[u8])] = &[\n");
        for (score, out) in list {
            t.push_str(&format!(
                "    ({:?}, include_bytes!({:?})),\n",
                stem(score),
                out.display().to_string()
            ));
        }
        t.push_str("];\n");
        t
    };
    std::fs::write(
        out_dir.join("scores.rs"),
        table("audio/score/*.score", "STUDIO", &scores),
    )
    .expect("write scores.rs");
    effects
        .into_iter()
        .map(|(s, out)| (stem(&s), out))
        .collect()
}

/// Hashes every file under `dir`, in name order, with its path.
#[cfg(feature = "audio")]
fn hash_tree(dir: &Path, hasher: &mut std::hash::DefaultHasher) {
    use std::hash::Hash;
    let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)
        .map(|d| d.filter_map(|e| e.ok().map(|e| e.path())).collect())
        .unwrap_or_default();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            hash_tree(&path, hasher);
        } else if let Ok(bytes) = std::fs::read(&path) {
            path.hash(hasher);
            bytes.hash(hasher);
        }
    }
}
